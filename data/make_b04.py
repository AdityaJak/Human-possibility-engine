"""Generate X3-B04 adaptive-comparator definitions for a family from that family's X3-B03 selected pop_gru."""
import json
import sys
from pathlib import Path

from hpe.core.rng import derive_seed

fam = sys.argv[1]
r = json.loads(Path(f"reports/phase3/baselines/x3_b03_pop_{fam}/parts/{fam}__pop_gru.json").read_text())
sel = r["selected"]
cfg = {k: sel["config"][k] for k in ("hidden", "lr", "dropout", "max_epochs", "patience", "batch_size")}
seed = derive_seed(20261108, fam, "pop_gru", sel["config_index"]) % (2**31 - 1)
tpl = Path("experiments/phase3/x3_b04_adapt_restless4.yaml").read_text()
tpl = tpl.replace("x3_b04_adapt_restless4", f"x3_b04_adapt_{fam}").replace("families: [restless4]", f"families: [{fam}]")
bb = "{" + ", ".join(f"{k}: {v}" for k, v in cfg.items()) + "}"
tpl = tpl.replace("{hidden: 32, lr: 0.01, dropout: 0.0, max_epochs: 150, patience: 10, batch_size: 8}", bb)
tpl = tpl.replace("273911918", str(seed)).replace("restless4 tune", f"{fam} tune")
tpl = tpl.replace("# X3-B04 restless4", f"# X3-B04 {fam} (generated by data/make_b04.py from the X3-B03 {fam} pop_gru selection)")
Path(f"experiments/phase3/x3_b04_adapt_{fam}.yaml").write_text(tpl)
print(f"wrote experiments/phase3/x3_b04_adapt_{fam}.yaml backbone {bb} seed {seed}")
