#!/usr/bin/env python3
"""Export frozen contracts to JSON Schema and TypeScript.

    python scripts/export_contracts.py          # write files
    python scripts/export_contracts.py --check  # exit 1 if generated files are stale (CI)

Outputs:
    packages/hpe/contracts/schema/contracts.schema.json
    apps/web/src/types/contracts.ts
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "packages"))

from hpe.contracts import api, schemas  # noqa: E402
from hpe.contracts.runtime import CONTRACT_VERSION  # noqa: E402

SCHEMA_OUT = ROOT / "packages/hpe/contracts/schema/contracts.schema.json"
TS_OUT = ROOT / "apps/web/src/types/contracts.ts"


def _models() -> list[type[BaseModel]]:
    out: list[type[BaseModel]] = []
    for mod in (schemas, api):
        for name in sorted(dir(mod)):
            obj = getattr(mod, name)
            if (
                isinstance(obj, type)
                and issubclass(obj, BaseModel)
                and obj.__module__ == mod.__name__
                and not name.startswith("_")
                and not getattr(obj, "__pydantic_generic_metadata__", {}).get("parameters")
            ):
                out.append(obj)
    return out


def build_schema() -> dict[str, Any]:
    _, top = models_json_schema([(m, "serialization") for m in _models()], ref_template="#/$defs/{model}")
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "HPE contracts",
        "version": CONTRACT_VERSION,
        **top,
    }


def _ts_type(s: dict[str, Any]) -> str:
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    if "anyOf" in s or "oneOf" in s:
        parts = [_ts_type(x) for x in s.get("anyOf", s.get("oneOf", []))]
        return " | ".join(dict.fromkeys(parts))
    if "allOf" in s and len(s["allOf"]) == 1:
        return _ts_type(s["allOf"][0])
    t = s.get("type")
    if isinstance(t, list):
        return " | ".join(_ts_type({**s, "type": x}) for x in t)
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(_ts_type(x) for x in s["prefixItems"]) + "]"
        inner = _ts_type(s.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        if "properties" in s:
            return _ts_object(s)
        ap = s.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return f"Record<string, {_ts_type(ap)}>"
        return "Record<string, unknown>"
    return "unknown"


def _ts_object(s: dict[str, Any], indent: str = "  ") -> str:
    req = set(s.get("required", []))
    lines = ["{"]
    for name, prop in s.get("properties", {}).items():
        opt = "" if name in req else "?"
        desc = prop.get("description")
        if desc:
            lines.append(f"{indent}/** {desc} */")
        lines.append(f"{indent}{name}{opt}: {_ts_type(prop)};")
    lines.append(indent[:-2] + "}")
    return "\n".join(lines)


def build_ts(schema: dict[str, Any]) -> str:
    out = [
        "/* eslint-disable */",
        "// AUTO-GENERATED by scripts/export_contracts.py from hpe.contracts — DO NOT EDIT BY HAND.",
        f"// Contract version {CONTRACT_VERSION}. Change the Pydantic models + ADR, then regenerate.",
        "",
        f'export const CONTRACT_VERSION = "{CONTRACT_VERSION}";',
        "",
    ]
    for name, d in sorted(schema.get("$defs", {}).items()):
        if d.get("description"):
            out.append("/** " + d["description"].strip().replace("*/", "* /").replace("\n", "\n * ") + " */")
        if d.get("type") == "object" and "properties" in d:
            out.append(f"export interface {name} {_ts_object(d)}")
        else:
            out.append(f"export type {name} = {_ts_type(d)};")
        out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    schema = build_schema()
    schema_text = json.dumps(schema, indent=2, sort_keys=True) + "\n"
    ts_text = build_ts(schema)
    if args.check:
        stale = [
            str(p.relative_to(ROOT))
            for p, txt in ((SCHEMA_OUT, schema_text), (TS_OUT, ts_text))
            if not p.exists() or p.read_text() != txt
        ]
        if stale:
            print(
                "stale generated contract files:",
                ", ".join(stale),
                "\nrun: python scripts/export_contracts.py",
            )
            return 1
        print("contracts up to date")
        return 0
    SCHEMA_OUT.parent.mkdir(parents=True, exist_ok=True)
    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    SCHEMA_OUT.write_text(schema_text)
    TS_OUT.write_text(ts_text)
    print(
        f"wrote {SCHEMA_OUT.relative_to(ROOT)} and {TS_OUT.relative_to(ROOT)} ({len(schema['$defs'])} types)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
