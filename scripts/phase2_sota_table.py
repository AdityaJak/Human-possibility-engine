#!/usr/bin/env python3
"""Render the Phase II comparison tables from a run2 summary.json (never hand-typed numbers).

    python scripts/phase2_sota_table.py reports/phase2/human/p2_human_dev_pilot > reports/phase2/human/p2_human_dev_pilot/sota_table.md

Produces, per paradigm: report-partition NLL with 95% CI, vs chance, top-1, ECE, NLL by trial quartile
(sample efficiency), parameter count, CPU seconds; plus the exploratory contrasts.
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

GROUP = {
    "developmental": "ours",
    "hybrid_exemplar": "ours",
    "memory_only": "ours (baseline)",
    "plain_rl": "ours (baseline)",
    "static_persona": "ours (baseline)",
    "random": "chance",
}


def f(x, nd=3):
    return "—" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{nd}f}"


def main() -> int:
    run = Path(sys.argv[1])
    s = json.loads((run / "summary.json").read_text())
    info = json.loads((run / "run_info.json").read_text())
    print(
        f"# Directly reproduced comparison — `{s['experiment_id']}` (report partition: **{s['report_partition']}**)"
    )
    print()
    print(
        f"_Generated by `scripts/phase2_sota_table.py` from `{run}/summary.json`; code `{info['code_version']}`; CPU {info['cpu_time_s']} s; 0 LLM calls. Every model saw identical observations and feedback (teacher forcing); grids ≤ 24 configurations each; shared lapse grid._"
    )
    print()
    for par, sp in s["paradigms"].items():
        print(f"## {par} ({sp['role']}) — n = {sp['n']}; chance NLL {sp['chance_nll']:.4f}")
        print()
        print(
            "| model | group | NLL [95% CI] | Δ chance | top-1 | ECE | Q1 | Q2 | Q3 | Q4 | params | CPU s | status |"
        )
        print("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
        for m, v in sorted(sp["models"].items(), key=lambda kv: kv[1].get("nll_mean", 99)):
            g = GROUP.get(m, "reference")
            if v.get("n_participants"):
                q = v["nll_by_quarter"]
                print(
                    f"| {m} | {g} | {f(v['nll_mean'], 4)} [{f(v['nll_ci_low'], 3)}, {f(v['nll_ci_high'], 3)}] | {v['minus_chance']:+.3f} | {f(v['top1_mean'])} | {f(v['ece_mean'])} | {f(q[0])} | {f(q[1])} | {f(q[2])} | {f(q[3])} | {v['param_count'] if v['param_count'] is not None else '—'} | {v['cpu_seconds']} | ok{' (grid edge: ' + ', '.join(v['grid_edges']) + ')' if v['grid_edges'] else ''} |"
                )
            else:
                print(
                    f"| {m} | {g} | — | — | — | — | — | — | — | — | — | {v['cpu_seconds']} | {v['status']}: {v['note'][:70]} |"
                )
        print()
        if sp["contrasts"]:
            print("| contrast | estimate | 95% CI | p | dz | n |")
            print("|---|---|---|---|---|---|")
            for c in sp["contrasts"]:
                print(
                    f"| {c['first']} − {c['second']} | {c['estimate']:+.4f} | [{c['ci_low']:+.4f}, {c['ci_high']:+.4f}] | {c['p_value']:.3g} | {f(c['dz'], 2)} | {c['n']} |"
                )
            print()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
