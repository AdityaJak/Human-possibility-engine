"""Phase II participant partitions and the test-partition lock.

The frozen partitions file (``reports/phase2/partitions/psych101.json``, generated by
``scripts/phase2_partitions.py``) assigns every participant of every experiment file to exactly one
of ``dev`` / ``tune`` / ``test``. Rules (docs/phase2/EXPERIMENT_REGISTRY.md):

* ``dev`` and ``tune`` may be read freely.
* ``test`` transcripts are never read, parsed, scored or looked at unless a **freeze record**
  ``reports/phase2/freeze/<id>.json`` exists. Filtering happens at the JSONL record level, before
  any transcript text is parsed, so a locked partition is never materialised in memory.
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Iterable, Iterator
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

Partition = Literal["dev", "tune", "test"]
PARTITIONS = ("dev", "tune", "test")

REPO_ROOT = Path(__file__).resolve().parents[4]
DEFAULT_PARTITIONS_FILE = REPO_ROOT / "reports" / "phase2" / "partitions" / "psych101.json"
DEFAULT_FREEZE_DIR = REPO_ROOT / "reports" / "phase2" / "freeze"


class TestPartitionLocked(PermissionError):
    """Raised when code tries to touch the test partition without a freeze record."""


@dataclass(frozen=True, slots=True)
class Partitions:
    split_seed: int
    families: dict[str, tuple[str, ...]]  # family -> experiment files
    assignment: dict[tuple[str, str], Partition]  # (experiment, participant) -> partition
    test_partition_sha256: str

    @classmethod
    def load(cls, path: Path = DEFAULT_PARTITIONS_FILE) -> Partitions:
        raw = json.loads(Path(path).read_text(encoding="utf-8"))
        families: dict[str, tuple[str, ...]] = {}
        assignment: dict[tuple[str, str], Partition] = {}
        for fam, exps in raw["families"].items():
            families[fam] = tuple(sorted(exps))
            for exp, v in exps.items():
                for part in PARTITIONS:
                    for pid in v[part]:
                        assignment[(exp, str(pid))] = part  # type: ignore[assignment]
        p = cls(int(raw["split_seed"]), families, assignment, raw["test_partition_sha256"])
        p.verify()
        return p

    def verify(self) -> None:
        """Recompute the test-partition digest; a mismatch means the frozen file was edited."""
        keys = sorted(f"{e}#{p}" for (e, p), part in self.assignment.items() if part == "test")
        digest = hashlib.sha256("\n".join(keys).encode()).hexdigest()
        if digest != self.test_partition_sha256:
            raise ValueError("partitions file test digest mismatch — frozen partitions were modified")

    def experiments_of(self, family: str) -> tuple[str, ...]:
        return self.families[family]

    def family_of(self, experiment: str) -> str | None:
        for fam, exps in self.families.items():
            if experiment in exps:
                return fam
        return None

    def counts(self, family: str) -> dict[str, int]:
        out = dict.fromkeys(PARTITIONS, 0)
        for (e, _), part in self.assignment.items():
            if e in self.families[family]:
                out[part] += 1
        return out


def freeze_record(experiment_id: str, freeze_dir: Path = DEFAULT_FREEZE_DIR) -> dict | None:
    p = Path(freeze_dir) / f"{experiment_id}.json"
    if not p.exists():
        return None
    rec = json.loads(p.read_text(encoding="utf-8"))
    required = {"experiment_id", "preregistration_hash", "code_version", "frozen_at"}
    missing = required - set(rec)
    if missing:
        raise ValueError(f"freeze record {p} is missing fields {sorted(missing)}")
    return rec


def check_partition_access(
    partition: str, experiment_id: str | None = None, freeze_dir: Path = DEFAULT_FREEZE_DIR
) -> None:
    """Allow dev/tune always; allow test only with a valid freeze record for ``experiment_id``."""
    if partition not in PARTITIONS:
        raise ValueError(f"unknown partition {partition!r}; expected one of {PARTITIONS}")
    if partition != "test":
        return
    if Path(freeze_dir).resolve() == DEFAULT_FREEZE_DIR.resolve():
        # Phase II ended (PIVOT) without any human test freeze; the test partitions of the families Phase III
        # reuses are governed by Phase III's stricter lock (hpe.population.core.freeze). Critic finding T-4.
        raise TestPartitionLocked(
            "Phase II is closed: its test partitions cannot be unlocked through Phase II tooling"
        )
    if experiment_id is None or freeze_record(experiment_id, freeze_dir) is None:
        raise TestPartitionLocked(
            "the test partition is locked: no freeze record "
            f"{Path(freeze_dir) / f'{experiment_id}.json'} exists. Develop and tune on dev/tune only; "
            "the Research Director creates the freeze record once model selection is final."
        )


def iter_partition_records(
    records: Iterable[dict],
    partitions: Partitions,
    partition: str,
    *,
    experiments: Iterable[str] | None = None,
    experiment_id: str | None = None,
    freeze_dir: Path = DEFAULT_FREEZE_DIR,
) -> Iterator[dict]:
    """Yield raw JSONL records of one partition. Test records are skipped unread unless unlocked."""
    check_partition_access(partition, experiment_id, freeze_dir)
    allowed_exps = set(experiments) if experiments is not None else None
    for rec in records:
        exp = rec["experiment"]
        if allowed_exps is not None and exp not in allowed_exps:
            continue
        part = partitions.assignment.get((exp, str(rec["participant"])))
        if part == partition:
            yield rec
