"""Run, persist, and (re)analyse human-data experiments.

Everything in ``result.json`` / ``summary.json`` / figures is regenerated by ``analyze_*`` from
files on disk (``fits.json`` + ``outcomes.jsonl.gz`` for exp07; ``estimates.json`` for exp07b),
never from in-memory objects. Only derived metrics are written; no raw external data.
"""

from __future__ import annotations

import gzip
import json
import math
from pathlib import Path
from typing import Any

import numpy as np

from hpe.contracts.schemas import ArmSummary, EffectEstimate, ExperimentResult, OutcomeObservation
from hpe.core.rng import stream
from hpe.evaluation.human.definition import CausalGroundingDefinition, HumanHeldoutDefinition

HUMAN_DISCLAIMER_7A = (
    "Result on real, externally sourced human data (Psych-101, Apache-2.0; Binz et al. 2024). It measures "
    "held-out one-step-ahead predictive fit to adult choices in short laboratory learning tasks. It is not a "
    "validation of the simulator's world, not a causal claim, and not evidence about any individual's future."
)
HUMAN_DISCLAIMER_7B = (
    "Real randomised-trial data (HeartSteps V1, CC-BY-4.0; Klasnja et al. 2019). Causal excursion effect of a "
    "mobile-health activity suggestion under the stated identification assumptions. Unrelated to, and not a "
    "validation of, any simulation result in this repository."
)
CHANCE = {"mcpl": math.log(9), "igt": math.log(4)}


# ----------------------------------------------------------------------------- io helpers
def write_json(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, sort_keys=True, default=str) + "\n", encoding="utf-8")


def read_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def write_outcomes(path: Path, rows: list[OutcomeObservation]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(path, "wt", encoding="utf-8") as f:
        for r in rows:
            f.write(r.model_dump_json() + "\n")


def read_outcomes(path: Path) -> list[OutcomeObservation]:
    with gzip.open(path, "rt", encoding="utf-8") as f:
        return [OutcomeObservation.model_validate_json(line) for line in f if line.strip()]


# ----------------------------------------------------------------------------- statistics
def bootstrap_mean(x: np.ndarray, n_boot: int, seed: int, *key: str) -> tuple[float, float, float, float]:
    """Mean, percentile 95% CI and two-sided bootstrap p-value (H0: mean = 0)."""
    rng = stream(seed, "human_bootstrap", *key)
    idx = rng.integers(0, len(x), size=(n_boot, len(x)))
    means = x[idx].mean(axis=1)
    lo, hi = np.quantile(means, [0.025, 0.975])
    # two-sided bootstrap p, floored at 1/n_boot (a bootstrap cannot resolve smaller p-values)
    p = float(min(1.0, max(1.0 / n_boot, 2 * min((means <= 0).mean(), (means >= 0).mean()))))
    return float(x.mean()), float(lo), float(hi), p


def status_from_contrast(est: float, lo: float, hi: float, mei: float) -> str:
    if hi < 0 and est <= -mei:
        return "passed"
    if lo > -mei:
        return "failed"
    return "inconclusive"


# ----------------------------------------------------------------------------- exp07 analysis
def _per_model(
    outcomes: list[OutcomeObservation], split_seed: int, paradigm: str, metric: str
) -> dict[str, dict[str, float]]:
    out: dict[str, dict[str, float]] = {}
    for o in outcomes:
        if o.seed != split_seed or o.metric != metric or o.arm is None:
            continue
        par, model = o.arm.split(":", 1)
        if par == paradigm and o.agent_id is not None:
            out.setdefault(model, {})[o.agent_id] = o.value
    return out


def _contrast(
    a: str,
    b: str,
    nll: dict[str, dict[str, float]],
    n_boot: int,
    seed: int,
    metric: str,
    mei: float,
    tag: str,
) -> dict[str, Any]:
    keys = sorted(set(nll[a]) & set(nll[b]))
    d = np.array([nll[a][k] - nll[b][k] for k in keys])
    est, lo, hi, p = bootstrap_mean(d, n_boot, seed, tag, a, b)
    sd = float(d.std(ddof=1)) if len(d) > 1 else float("nan")
    return {
        "contrast": f"{a} - {b}",
        "metric": metric,
        "estimate": est,
        "ci_low": lo,
        "ci_high": hi,
        "p_value": p,
        "cohen_dz": est / sd if sd and sd > 0 else None,
        "n_participants": len(keys),
        "status": status_from_contrast(est, lo, hi, mei),
    }


def analyze_exp07(outdir: Path) -> tuple[ExperimentResult, dict[str, Any]]:
    defn = HumanHeldoutDefinition.model_validate(read_json(outdir / "definition.json"))
    fits = read_json(outdir / "fits.json")
    outcomes = read_outcomes(outdir / "outcomes.jsonl.gz")
    n_boot = defn.analysis.n_bootstrap
    mei = defn.analysis.minimum_effect_of_interest
    static = set(defn.model_groups.get("static", []))
    adaptive = set(defn.model_groups.get("adaptive", []))
    summary: dict[str, Any] = {"preregistration_hash": defn.preregistration_hash, "splits": {}}
    arms: list[ArmSummary] = []
    effects: list[EffectEstimate] = []
    primary: dict[str, Any] | None = None
    primary_split = defn.split.seed

    for split_key, split_fits in sorted(fits.items(), key=lambda kv: int(kv[0])):
        split_seed = int(split_key)
        ssum: dict[str, Any] = {}
        for paradigm, pf in sorted(split_fits.items()):
            metric = f"heldout_nll_per_choice_{paradigm}"
            nll = _per_model(outcomes, split_seed, paradigm, "nll_per_choice")
            top1 = _per_model(outcomes, split_seed, paradigm, "top1_accuracy")
            ok = {m: f for m, f in pf["models"].items() if f["status"] == "ok" and m in nll}
            table = []
            for m, f in pf["models"].items():
                row: dict[str, Any] = {"model": m, "status": f["status"], "note": f.get("note", "")}
                if m in ok:
                    x = np.array([nll[m][k] for k in sorted(nll[m])])
                    mean, lo, hi, _ = bootstrap_mean(x, n_boot, split_seed, "arm", paradigm, m)
                    t = np.array([top1[m][k] for k in sorted(top1[m])])
                    row.update(
                        train_objective=f["train_objective"],
                        params=f["params"],
                        lapse=f["lapse"],
                        test_nll_mean=mean,
                        test_nll_ci_low=lo,
                        test_nll_ci_high=hi,
                        test_nll_sd=float(x.std(ddof=1)),
                        test_top1_mean=float(t.mean()),
                        n_test=len(x),
                        minus_chance=mean - CHANCE[paradigm],
                    )
                    if split_seed == primary_split:
                        tm, tlo, thi, _ = bootstrap_mean(t, n_boot, split_seed, "arm_top1", paradigm, m)
                        arms.append(
                            ArmSummary(
                                arm=f"{paradigm}:{m}",
                                n_runs=len(x),
                                metrics={
                                    metric: {
                                        "mean": mean,
                                        "sd": row["test_nll_sd"],
                                        "ci_low": lo,
                                        "ci_high": hi,
                                        "n": len(x),
                                    },
                                    f"heldout_top1_{paradigm}": {
                                        "mean": tm,
                                        "sd": float(t.std(ddof=1)),
                                        "ci_low": tlo,
                                        "ci_high": thi,
                                        "n": len(t),
                                    },
                                },
                            )
                        )
                table.append(row)

            def best(cands: set[str], ok: dict[str, dict] = ok) -> str | None:
                c = [m for m in cands if m in ok]
                return min(c, key=lambda m: ok[m]["train_objective"]) if c else None

            non_dev = best({m for m in ok if m not in ("random", "developmental")})
            b_adapt, b_static = best(adaptive), best(static)
            contrasts: list[dict[str, Any]] = []
            dev_contrast = None
            if "developmental" in ok and non_dev:
                dev_contrast = _contrast(
                    "developmental", non_dev, nll, n_boot, split_seed, metric, mei, f"dev_{paradigm}"
                )
                contrasts.append({**dev_contrast, "role": "primary" if paradigm == "mcpl" else "secondary"})
            if b_adapt and b_static:
                contrasts.append(
                    {
                        **_contrast(
                            b_adapt, b_static, nll, n_boot, split_seed, metric, mei, f"as_{paradigm}"
                        ),
                        "role": "secondary",
                        "label": "best_adaptive - best_static",
                    }
                )
            ssum[paradigm] = {
                "chance_nll": CHANCE[paradigm],
                "n_train": pf["n_train"],
                "n_test": pf["n_test"],
                "best_non_developmental_on_train": non_dev,
                "best_adaptive_on_train": b_adapt,
                "best_static_on_train": b_static,
                "models": table,
                "contrasts": contrasts,
                "developmental_available": "developmental" in ok,
            }
            if split_seed == primary_split:
                for c in contrasts:
                    effects.append(
                        EffectEstimate(
                            metric=c["metric"],
                            contrast=c["contrast"] + (" [primary]" if c["role"] == "primary" else ""),
                            estimate=c["estimate"],
                            ci_low=c["ci_low"],
                            ci_high=c["ci_high"],
                            p_value=c["p_value"],
                            standardized_effect=c["cohen_dz"],
                            n_units=c["n_participants"],
                            unit_of_analysis="participant",
                            method=f"paired bootstrap over held-out participants ({n_boot} resamples)",
                            passed_minimum_effect=c["status"] == "passed",
                        )
                    )
                if paradigm == "mcpl":
                    primary = dev_contrast
        summary["splits"][split_key] = ssum

    if primary is None:
        status, reason = (
            "inconclusive",
            "Primary contrast not evaluated: the 'developmental' policy class is not available in this build "
            "(see per-model notes). Reference and baseline models were evaluated; see secondary contrasts.",
        )
    else:
        status = primary["status"]
        reason = (
            f"Primary contrast {primary['contrast']} on held-out MCPL participants: {primary['estimate']:+.4f} nats/choice "
            f"(95% CI [{primary['ci_low']:+.4f}, {primary['ci_high']:+.4f}], n={primary['n_participants']}); "
            f"minimum effect of interest {mei} nats/choice; rule: {defn.analysis.status_rule}"
        )
    result = ExperimentResult(
        experiment_id=defn.experiment_id,
        preregistration_hash=defn.preregistration_hash or "",
        status=status,  # type: ignore[arg-type]
        status_reason=reason,
        arms=arms,
        effects=effects,
        run_ids=[f"split{k}" for k in sorted(fits, key=int)],
        sensitivity=[
            {"split_seed": int(k), **{p: [c for c in v["contrasts"]] for p, v in s.items()}}
            for k, s in summary["splits"].items()
            if int(k) != primary_split
        ],
        figures=["figures/heldout_nll_mcpl.png", "figures/heldout_nll_igt.png"],
        limitations=list(defn.validity_notes),
        synthetic_disclaimer=HUMAN_DISCLAIMER_7A,
        generated_from="fits.json + outcomes.jsonl.gz (derived per-participant held-out metrics)",
        created_at=read_json(outdir / "run_info.json")["created_at"],
    )
    return result, summary


# ----------------------------------------------------------------------------- figures
def plot_exp07(summary: dict[str, Any], primary_split: int, figdir: Path) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    figdir.mkdir(parents=True, exist_ok=True)
    out = []
    for paradigm, s in summary["splits"][str(primary_split)].items():
        rows = [r for r in s["models"] if "test_nll_mean" in r]
        rows.sort(key=lambda r: r["test_nll_mean"])
        fig, ax = plt.subplots(figsize=(7.5, 0.45 * len(rows) + 1.6), dpi=130)
        y = np.arange(len(rows))
        means = np.array([r["test_nll_mean"] for r in rows])
        err = np.array(
            [
                [r["test_nll_mean"] - r["test_nll_ci_low"], r["test_nll_ci_high"] - r["test_nll_mean"]]
                for r in rows
            ]
        ).T
        err = np.clip(err, 0.0, None)  # constant-NLL models (random) give ~1e-16 negative widths
        ax.errorbar(means, y, xerr=err, fmt="o", color="#1f5f8b", capsize=3)
        ax.axvline(
            s["chance_nll"],
            color="#a33",
            ls="--",
            lw=1,
            label=f"chance (ln {9 if paradigm == 'mcpl' else 4})",
        )
        ax.set_yticks(y, [r["model"] for r in rows])
        ax.invert_yaxis()
        ax.set_xlabel("held-out NLL per choice (lower is better), 95% bootstrap CI")
        ax.set_title(f"{paradigm.upper()}: held-out human participants (n={s['n_test']}) — real human data")
        ax.legend(loc="lower left", fontsize=8)
        fig.tight_layout()
        p = figdir / f"heldout_nll_{paradigm}.png"
        fig.savefig(p)
        plt.close(fig)
        out.append(p)
    return out


def plot_exp07b(estimates: dict[str, Any], figdir: Path) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    figdir.mkdir(parents=True, exist_ok=True)
    prim = estimates["primary"]["terms"]
    fig, ax = plt.subplots(figsize=(7, 3.2), dpi=130)
    labels, ests, los, his = [], [], [], []
    for t in prim:
        labels.append(t["term"])
        ests.append(100 * math.expm1(t["estimate"]))
        los.append(100 * math.expm1(t["ci_low_bootstrap"]))
        his.append(100 * math.expm1(t["ci_high_bootstrap"]))
    y = np.arange(len(labels))
    ax.errorbar(
        ests,
        y,
        xerr=np.clip([np.array(ests) - np.array(los), np.array(his) - np.array(ests)], 0.0, None),
        fmt="o",
        color="#1f5f8b",
        capsize=3,
        label="this analysis (95% cluster bootstrap CI)",
    )
    for pv in estimates["published"]:
        if pv["term"] in labels:
            ax.plot(
                pv["published_percent"],
                labels.index(pv["term"]),
                "D",
                color="#c77b00",
                label=f"published ({pv['term']})",
            )
    ax.axvline(0, color="#777", lw=0.8)
    ax.set_yticks(y, labels)
    ax.invert_yaxis()
    ax.set_xlabel("% change in 30-min step count (exp(beta) - 1)")
    ax.set_title("HeartSteps V1 — real micro-randomised trial data")
    ax.legend(fontsize=7, loc="lower right")
    fig.tight_layout()
    p1 = figdir / "effects_vs_published.png"
    fig.savefig(p1)
    plt.close(fig)

    tm = estimates["time_moderated"]
    days = np.arange(0, tm["max_day"] + 1)
    eff = 100 * np.expm1(tm["beta0"] + tm["beta1"] * (days - tm["day_centre"]))
    fig, ax = plt.subplots(figsize=(7, 3), dpi=130)
    ax.plot(days, eff, color="#1f5f8b")
    ax.axhline(0, color="#777", lw=0.8)
    ax.set_xlabel("study day")
    ax.set_ylabel("% change (any suggestion)")
    ax.set_title("Time-moderated excursion effect (linear in study day)")
    fig.tight_layout()
    p2 = figdir / "effect_by_study_day.png"
    fig.savefig(p2)
    plt.close(fig)
    return [p1, p2]


# ----------------------------------------------------------------------------- exp07b analysis
def analyze_exp07b(outdir: Path) -> ExperimentResult:
    defn = CausalGroundingDefinition.model_validate(read_json(outdir / "definition.json"))
    est = read_json(outdir / "estimates.json")
    effects = []
    comparisons = []
    for t in est["primary"]["terms"]:
        pub = next((p for p in est["published"] if p["term"] == t["term"]), None)
        effects.append(
            EffectEstimate(
                metric="log(jbsteps30.zero + 0.5)",
                contrast=f"{t['term']} vs no suggestion",
                estimate=t["estimate"],
                ci_low=t["ci_low_bootstrap"],
                ci_high=t["ci_high_bootstrap"],
                p_value=t["p_value"],
                n_units=est["primary"]["n_clusters"],
                unit_of_analysis="participant (cluster)",
                method=f"WCLS (centred least squares), participant-cluster bootstrap ({t['n_bootstrap']} resamples); sandwich t({t['df']}) p-value",
                passed_minimum_effect=None,
            )
        )
        if pub is not None:
            target = math.log1p(pub["published_percent"] / 100)
            comparisons.append(
                {
                    "term": t["term"],
                    "published_log_effect": target,
                    "inside_ci": t["ci_low_bootstrap"] <= target <= t["ci_high_bootstrap"],
                    "same_sign": (t["estimate"] > 0) == (target > 0),
                }
            )
    prim = next(c for c in comparisons if c["term"] == "any_suggestion")
    status = "passed" if prim["inside_ci"] else "failed"
    p0 = est["primary"]["terms"][0]
    reason = (
        f"any_suggestion: estimate {100 * math.expm1(p0['estimate']):+.1f}% (95% cluster bootstrap CI "
        f"[{100 * math.expm1(p0['ci_low_bootstrap']):+.1f}%, {100 * math.expm1(p0['ci_high_bootstrap']):+.1f}%]); "
        f"published +14% (p = .06) {'lies inside' if prim['inside_ci'] else 'lies outside'} the CI. Rule: {defn.comparison_rule}"
    )
    return ExperimentResult(
        experiment_id=defn.experiment_id,
        preregistration_hash=defn.preregistration_hash or "",
        status=status,  # type: ignore[arg-type]
        status_reason=reason,
        arms=[],
        effects=effects,
        run_ids=["heartsteps_v1_suggestions"],
        sensitivity=[{"variant": k, "terms": v["terms"]} for k, v in est["sensitivity"].items()]
        + [{"comparisons_with_published": comparisons}],
        figures=["figures/effects_vs_published.png", "figures/effect_by_study_day.png"],
        limitations=list(defn.validity_notes),
        synthetic_disclaimer=HUMAN_DISCLAIMER_7B,
        generated_from="estimates.json (computed directly from the verified HeartSteps V1 suggestions.csv)",
        created_at=est["created_at"],
    )
